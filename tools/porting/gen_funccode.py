#!/usr/bin/env python3
"""
gen_funccode.py - Funccode_enum.h / Funccode_define.h の Python 生成器

Phase 11 で導入。upstream の HeaderMake.exe (Win32 限定) を Python に移植。

upstream の元実装:
    tools/HeaderMake/HeaderMake.cpp
    sakura_core/Funccode_x.hsrc を入力に Funccode_enum.h と
    Funccode_define.h を生成する。

入力:
    sakura_core/Funccode_x.hsrc — 数百行の "ID = VALUE," 形式

出力:
    -mode=enum   → enum EFunctionCode { ID = VALUE, ... };
    -mode=define → #define ID VALUE が並ぶ

upstream HeaderMake.cpp とのアルゴリズム互換性:
1. C プリプロセッサ通過 (本実装では .hsrc が指令を含まない前提でスキップ可能)
2. 各行を空白／非 identifier 文字でトークナイズ
3. 先頭 identifier = ID、次の identifier = VALUE
4. 両方非空なら enum or define 形式で出力
5. ヘッダ／フッタは upstream と同じ include guard を使う

使用例:
    python3 tools/porting/gen_funccode.py \\
        --in sakura_core/Funccode_x.hsrc \\
        --out build/generated/Funccode_enum.h \\
        --mode enum --enum EFunctionCode
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# is_token() に対応: identifier 文字 (alnum/_) または '-' を 1 トークンとして許容
TOKEN_RE = re.compile(r"[A-Za-z_][A-Za-z_0-9]*|-?[0-9][A-Za-z_0-9]*|-")


def strip_comments(text: str) -> str:
    """C/C++ コメント (// と /* */) を除去。upstream HeaderMake は gcc -E で
    プリプロセス通過させてコメント除去するため、Python 版でも同等処理する。"""
    out: list[str] = []
    i = 0
    n = len(text)
    in_block = False
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if in_block:
            if c == "*" and nxt == "/":
                in_block = False
                i += 2
            else:
                # ブロックコメント中、改行は保持して行番号一致を維持
                out.append("\n" if c == "\n" else " ")
                i += 1
        else:
            if c == "/" and nxt == "/":
                # 行末まで読み飛ばし
                while i < n and text[i] != "\n":
                    i += 1
                # 改行はそのまま追加
                if i < n:
                    out.append("\n")
                    i += 1
            elif c == "/" and nxt == "*":
                in_block = True
                i += 2
            else:
                out.append(c)
                i += 1
    return "".join(out)


def parse_hsrc(text: str) -> list[tuple[str, str]]:
    """各行から (id, value) ペアを抽出。空ペアは破棄。
    入力は strip_comments() でコメント除去済みであること。"""
    pairs: list[tuple[str, str]] = []
    for raw in text.splitlines():
        # # 指令行はスキップ (HeaderMake.cpp も "#" 始まりはスキップしている)
        stripped = raw.lstrip()
        if stripped.startswith("#"):
            continue
        # enum 宣言や閉じ波括弧などの C++ 構文行は弾く
        if stripped.startswith("enum") or stripped.startswith("}"):
            continue
        if "{" in raw:
            continue
        # 行内のトークンを順番に抽出
        tokens = TOKEN_RE.findall(raw)
        if len(tokens) < 2:
            continue
        # 先頭 2 トークンを id / value とみなす
        id_token = tokens[0]
        value_token = tokens[1]
        if not id_token or not value_token:
            continue
        # id は識別子で始まる必要がある (純数値の id は弾く)
        if not (id_token[0].isalpha() or id_token[0] == "_"):
            continue
        pairs.append((id_token, value_token))
    return pairs


def emit_enum(pairs: list[tuple[str, str]], enum_name: str, src_name: str) -> str:
    out = ["/*! @file */"]
    out.append("#ifndef SAKURA_HEADERMAKE_2034D8F5_AE65_408D_9F53_D3DEA240C67BI_H_")
    out.append("#define SAKURA_HEADERMAKE_2034D8F5_AE65_408D_9F53_D3DEA240C67BI_H_")
    out.append("")
    out.append(f"// This file is generated by gen_funccode.py with {src_name}.")
    out.append("// Don't edit this file manually.")
    out.append("")
    out.append(f"enum {enum_name}" + "{")
    for id_, value in pairs:
        out.append(f"\t{id_} = {value},")
    out.append("};")
    out.append("")
    out.append("#endif /* SAKURA_HEADERMAKE_2034D8F5_AE65_408D_9F53_D3DEA240C67BI_H_ */")
    out.append("")
    return "\n".join(out)


def emit_define(pairs: list[tuple[str, str]], src_name: str) -> str:
    out = ["/*! @file */"]
    out.append("#ifndef SAKURA_HEADERMAKE_98B26AB2_D5C9_4884_8D15_D1F3A2936253_H_")
    out.append("#define SAKURA_HEADERMAKE_98B26AB2_D5C9_4884_8D15_D1F3A2936253_H_")
    out.append("")
    out.append(f"// This file is generated by gen_funccode.py with {src_name}.")
    out.append("// Don't edit this file manually.")
    out.append("")
    for id_, value in pairs:
        out.append(f"#define {id_} {value}")
    out.append("")
    out.append("#endif /* SAKURA_HEADERMAKE_98B26AB2_D5C9_4884_8D15_D1F3A2936253_H_ */")
    out.append("")
    return "\n".join(out)


def main() -> int:
    p = argparse.ArgumentParser(description="Generate Funccode_enum.h / Funccode_define.h")
    p.add_argument("--in", dest="in_file", required=True, help="Input .hsrc path")
    p.add_argument("--out", dest="out_file", required=True, help="Output .h path")
    p.add_argument("--mode", choices=["enum", "define"], required=True)
    p.add_argument("--enum", dest="enum_name", default="EFunctionCode",
                   help="Enum name (mode=enum only)")
    args = p.parse_args()

    in_path = Path(args.in_file)
    out_path = Path(args.out_file)

    if not in_path.exists():
        print(f"ERROR: input not found: {in_path}", file=sys.stderr)
        return 2

    # 入力ファイル文字コード判定: BOM 付き UTF-8 を許容
    raw = in_path.read_bytes()
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
    text = raw.decode("utf-8", errors="replace")

    text = strip_comments(text)
    pairs = parse_hsrc(text)
    if not pairs:
        print(f"WARN: no id/value pairs found in {in_path}", file=sys.stderr)

    src_name = in_path.name
    if args.mode == "enum":
        rendered = emit_enum(pairs, args.enum_name, src_name)
    else:
        rendered = emit_define(pairs, src_name)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    # 既存と内容が同じなら touch しない (CMake 再ビルド抑制)
    if out_path.exists():
        existing = out_path.read_text(encoding="utf-8")
        if existing == rendered:
            print(f"OK (no change): {out_path} ({len(pairs)} entries)")
            return 0
    out_path.write_text(rendered, encoding="utf-8")
    print(f"OK: wrote {out_path} ({len(pairs)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
